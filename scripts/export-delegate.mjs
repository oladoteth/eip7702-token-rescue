// Writes the compiled RescueDelegate ABI and bytecode into the app.
// Run after `forge build`: node scripts/export-delegate.mjs
import { readFileSync, writeFileSync } from 'node:fs';

const artifact = JSON.parse(readFileSync('out/RescueDelegate.sol/RescueDelegate.json', 'utf8'));
const body = `// Generated by scripts/export-delegate.mjs from contracts/RescueDelegate.sol. Do not edit.
export const RESCUE_DELEGATE_ABI = ${JSON.stringify(artifact.abi, null, 2)};

export const RESCUE_DELEGATE_BYTECODE = '${artifact.bytecode.object}';
`;
writeFileSync('src/contracts/rescueDelegate.js', body);
console.log('wrote src/contracts/rescueDelegate.js');
